import { CLOSING, OPENING } from "@/lib/text";

function shortTopic(topic: string): string {
  const clean = topic.replace(/\s+/g, " ").trim();
  if (clean.length <= 72) return clean;
  return `${clean.slice(0, 71).replace(/\s+\S*$/, "")}…`;
}

function holiday(topic: string): boolean {
  return /שבת|חג|פסח|שנה טובה|כיפור|חנוכה|פורים|סוכות|שבועות/.test(topic);
}

function wrap(body: string): string {
  return `${OPENING}\n\n${body.trim()}\n\n${CLOSING}`;
}

export function mockPost(topic: string, variant: number): string {
  const subject = shortTopic(topic);
  const wine = holiday(topic) ? "\n🍷" : "";
  const which = ((variant % 6) + 6) % 6;

  if (which === 0) {
    return wrap(`רציתם להבין מהי הגמוניה? תראו קטע: ${subject}.

זה לא ${subject}. זה סעיף מובהק של "ההגמוניה הבלתי מודעת להגמוניותה". (בחיי)

ישראל השנייה המתוקה רק ביקשה לעבור את היום. הפריווילגים מהעשירון העליון קבעו שזה "הסדר הטבעי": אתם נעצרים\\ממתינים\\מתנצלים, והם ממשיכים.

ככה עשו לבגין, ככה עשו לדרעי, וככה עושים היום ל${subject}. לא בשנות החמישים. היום. (גם כרגיל)

אוהבים אתכם ומתים לפיוס.

הגמוניה.${wine}`);
  }

  if (which === 1) {
    return wrap(`נו, כבר מסתמן איך ההגמוניה הופכת את ${subject} מאור לחושך, מתוק למר?

זו הרי אחת ממשימות העל של האליטה מאז מהפך 77: שלא חס וחלילה יהיה מצב רוח טוב, גם לא סביב ${subject}. (לא כולה, אבל מספיק)

ככה זה גם בחיים שלכם: אתה תהיה מוצלח בהרבה, אבל תיחסם\\תודח\\תתבקש לחכות. הפנקס האדום לא נעלם. הוא פשוט עבר ל${subject}.

פיוס ואחדות. הלוואי.

כמה עמוק הדיכוי.${wine}`);
  }

  if (which === 2) {
    return wrap(`מה אוהבי הצדק והשוויון חייבים ללמוד מ${subject}:

א. "זה סתם עניין קטן" הוא שקר שנועד לשמור על "הסדר הטבעי".

ב. אז מה האמת:
1. ישראל שנייה נחסמת\\מפוטרת\\נדחקת גם כשמדובר ב${subject}. היום, לא בשנות ה-50. (בחיי)
2. הפריווילג הבינוני עובר בלי לעמוד בתור. (גם כרגיל)

כמה סימבולי. תיאוריית ישראל השנייה כותבת את ההיסטוריה, גם כאן.

אוהבים אתכם ומתים לפיוס.${wine}`);
  }

  if (which === 3) {
    return wrap(`מזכיר בעדינות: ${subject} הוא לא ויכוח על נימוס. הוא שיעור על מבני העל של הדיכוי.

ההגמוניה בטוחה שהתור, הכלל והמזגן הם "אובייקטיבי המוחלט". מי ששואל למה דווקא הוא מחכה, נשמע לה פתאום מסוכן. (בחיי)

ככה עשו לבגין, ככה עשתה ההגמוניה למרן, וככה עושים עכשיו למי שרק רצה ${subject}. רחבה רחבה רחבה ההתנשאות, וצרה הסבלנות.

הבשורה המתוקה, המתונה, הסובלנית והאוהבת עדיין כאן. (ראו בספרי)

זה מרשים.${wine}`);
  }

  if (which === 4) {
    return wrap(`מרותק מול הציוד המתוקתק סביב ${subject}. אצל הפריווילגים מהעשירונים העליונים תמיד יש מישהו שמביא את הבריסטול. (גם כרגיל)

ואיפה ישראל השנייה? מעבירה שאלה בין כולם: "למישהו יש פתרון?" "מישהו יכול להזיז את ${subject}?" "לאף אחד אין מפתח?"

זה לא רק ${subject}. זה גם קרב על דימוי: מי רשאי להתלונן, ומי מתבקש להגיד תודה.

לתת. לתת. לתת. ואז לשמוע שזה "הסדר הטבעי".

הדיכוי משחית!${wine}`);
  }

  return wrap(`אחלה ${subject}. באמת. (בחיי)

אבל שימו לב איך מהר זה הופך להוכחה: ההגמוניה הבלתי מודעת להגמוניותה מסבירה לכם ש${subject} הוא בעצם אשמתכם, בזמן שהפריווילג עומד בצד וקורא לזה שוויון הזדמנויות.

מאז מהפך 77 אותו דפוס. לא בשנות החמישים. היום.

ככה זה גם בחיים שלכם. (לא כולה, מספיק כדי להבין)

פיוס ואחדות. הלוואי.
הערב, בתיאוריה.${wine}`);
}
